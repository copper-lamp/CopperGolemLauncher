// Run with node frontend/scripts/test-errtips.mjs. Uses existing TypeScript, no install/build.
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import ts from 'typescript';
const source = await fs.readFile(new URL('../src/services/errtips.ts', import.meta.url), 'utf8');
const js = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } }).outputText.replace(/from ['"]vue['"]/, `from '${import.meta.resolve('vue')}'`);
const service = await import(`data:text/javascript;base64,${Buffer.from(js).toString('base64')}`);
assert.equal(service.ruleFor({ timeout_scope: 'ipc', source: 'frontend' }), 'ipc_timeout');
assert.equal(service.ruleFor({ timeout_scope: 'daemon_rpc', source: 'lipd' }), 'daemon_timeout');
assert.equal(service.ruleFor({ timeout_scope: 'network', source: 'reqwest' }), 'network_timeout');
assert.equal(service.ruleFor({ timeout_scope: 'network', source: 'untrusted' }), 'unknown');
assert.equal(service.ruleFor({ http_status: 401 }), 'access_rejected');
assert.equal(service.ruleFor({ code: 'account_unclassified' }), 'entitlement_unknown');
assert.equal(service.ruleFor({ code: 'NotEntitled' }), 'unknown');
assert.equal(service.ruleFor({ http_status: 429 }), 'rate_limit');
assert.equal(service.ruleFor({ code: 'service_refused' }), 'service_refused');
const error = Object.assign(new Error('Authorization: Bearer PRIVATE https://host/?token=SECRET D:/Users/private'), { context: { source: 'reqwest', code: 'network_connect', host: 'private-user.example', operation: 'https://secret/path', retry_safe: true, os_code: 5 } });
const report = service.reportError(error);
assert.equal(service.reportError(error), report);
const diagnostic = service.diagnosticText(report);
for (const sensitive of ['PRIVATE', 'SECRET', 'private-user', 'https://', 'D:/Users']) assert.ok(!diagnostic.includes(sensitive));
assert.equal(report.context.retry_safe, false);
assert.equal(report.context.os_code, 5);
assert.equal(service.reportForMessage(error.message), report);
assert.throws(() => service.registerErrorRules('addon', [{code:'kernel.unknown',titleKey:'module.addon.title',bodyKey:'module.addon.body'}], () => true));
let authorized = true;
const dispose = service.registerErrorRules('addon', [{code:'addon.failure',titleKey:'module.addon.title',bodyKey:'module.addon.body'}], () => authorized);
const addon = service.reportError({}, { module: 'addon', code: 'addon.failure' });
assert.equal(service.contributedText(addon).titleKey, 'module.addon.title');
authorized = false;
assert.equal(service.contributedText(addon), undefined);
authorized = true;
dispose();
assert.equal(service.contributedText(addon), undefined);
for (let i=0;i<100;i++) service.reportError({}, { code: 'unknown' });
assert.equal(service.errorReports.value.length, 50);
let executions = 0;
let stopped = false;
const retryReport = service.reportError({}, { operation: 'readonly.refresh', retry_safe: true });
assert.equal(await service.runSafeRetry(retryReport), false);
const unregister = service.registerSafeRetry('readonly.refresh', { isIdempotent: true, isAuthorized: () => authorized,
  isPreviousOperationStopped: async () => stopped, execute: async () => { executions++; } });
assert.equal(await service.runSafeRetry(retryReport), false);
stopped = true; authorized = false;
assert.equal(await service.runSafeRetry(retryReport), false);
authorized = true;
assert.equal(await service.runSafeRetry(retryReport), true);
assert.equal(executions, 1);
unregister();
assert.equal(await service.runSafeRetry(retryReport), false);
console.log('errtips: safety/domain/dedup/permission/bounds and guarded retry assertions passed');
